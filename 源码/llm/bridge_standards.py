# 关键词匹配检索
# ============================================================
def search_standards(query: str, top_k: int = 3) -> list:
    """根据用户问题关键词检索相关国标条文"""
    scored = []
    for keyword, entries in STANDARDS.items():
        if keyword in query:
            for entry in entries:
                scored.append((1.0, entry))  # exact match
        else:
            # partial match on overlap
            overlap = len(set(keyword) & set(query)) / max(len(keyword), 1)
            if overlap > 0.3:
                for entry in entries:
                    scored.append((overlap * 0.5, entry))

    scored.sort(key=lambda x: -x[0])
    seen = set()
    results = []
    for score, entry in scored:
        key = entry["text"][:60]
        if key not in seen:
            seen.add(key)
            results.append(entry)
    return results[:top_k]


def enrich_prompt(question: str, top_k: int = 3) -> str:
    """将相关国标条文注入 prompt"""
    entries = search_standards(question, top_k)
    if not entries:
        return question

    standards_text = "\n\n".join(
        f"【{e['source']} §{e['section']}】\n{e['text']}"
        for e in entries
    )
    return (
        f"请依据以下桥梁检测规范回答用户问题。在回答中请引用相关规范条文。\n\n"
        f"{standards_text}\n\n"
        f"用户问题: {question}"
    )


